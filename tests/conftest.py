def gradient(w: int, h: int) -> Image.Image:
    """A smooth picture: its seams score low only when every tile is in place."""
    x = np.arange(w)[None, :].repeat(h, 0)
    y = np.arange(h)[:, None].repeat(w, 1)
    arr = np.stack([x * 255 // (w - 1), y * 255 // (h - 1), (x + y) * 255 // (w + h - 2)], axis=-1)
    return Image.fromarray(arr.astype(np.uint8))


def scramble(pic: Image.Image, swaps: List[int], k: int) -> Image.Image:
    """Move the tiles of pic so that the first k swaps put them back."""
    n = 5
    perm = list(range(n * n))
    for s in range(k):
        a, b = swaps[2 * s], swaps[2 * s + 1]
        perm[a], perm[b] = perm[b], perm[a]
    inverse = [0] * len(perm)
    for d, s in enumerate(perm):
        inverse[s] = d
    solver = SliderCaptchaSolver()
    layout = solver.compute_tile_layout(pic.size[0], pic.size[1], n)
    return solver.apply_tile_permutation(pic, layout, inverse, pic.size[0], pic.size[1], "png")


def encode_png(img: Image.Image) -> str:
    buf = io.BytesIO()
    img.save(buf, "PNG")
    return base64.b64encode(buf.getvalue()).decode()


def encode_jpeg(img: Image.Image) -> str:
    buf = io.BytesIO()
    img.save(buf, "JPEG", quality=90)
    return base64.b64encode(buf.getvalue()).decode()


