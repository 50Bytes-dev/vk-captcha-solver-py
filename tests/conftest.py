def probe_script(sc, order: List[str]) -> str:
    """A proof of work script that defines the probes of sc as VK's does, the
    fast ones as 'name':function and the rest as calls, and is called with
    order."""
    defs, calls = [], []
    for i, name in enumerate(sc.tel.keys):
        if i < len(sc.fast_probes):
            defs.append("'" + name + "':function(){return 1;}")
        else:
            calls.append("await _0x90c457('" + name + "',async function(){return 1;},0x64),")
    quoted = ",".join(json.dumps(n) for n in order)
    return (
        "(function(_0x3e7afa,_0x498b75,_0x244d4a,_0x5f4efb){var _0x1f4cdc={"
        + ",".join(defs)
        + "};"
        + "".join(calls)
        + "}('"
        + TEST_POW_INPUT
        + "',2,'pow_timeout',["
        + quoted
        + "]));"
    )


