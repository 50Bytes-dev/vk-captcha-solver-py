class FakeCall:
    """One request the fake VK received."""

    def __init__(self, request: web.Request, raw: bytes) -> None:
        self.http_method = request.method
        self.host = (request.host or "").split(":")[0]
        self.path = request.path
        self.query = {k: v for k, v in parse_qs(request.query_string, keep_blank_values=True).items()}
        self.raw_body = raw.decode("utf-8", "replace")
        self.form = parse_qs(self.raw_body, keep_blank_values=True) if request.method == "POST" else {}
        self.headers = CIMultiDict(request.headers)
        self.cookies = dict(request.cookies)
        self.cookie_header = request.headers.get("Cookie", "")

    def key(self) -> str:
        """host/path for pages, the method name for API calls."""
        if self.host in API_HOSTS:
            return self.path[len("/method/") :] if self.path.startswith("/method/") else self.path
        return self.host + self.path

    def f(self, name: str) -> Optional[str]:
        """The form's value of name, or None."""
        v = self.form.get(name)
        return v[0] if v else None

    def q(self, name: str) -> Optional[str]:
        v = self.query.get(name)
        return v[0] if v else None

    def form_keys(self) -> List[str]:
        return [kv.split("=", 1)[0] for kv in self.raw_body.split("&")]

    def __repr__(self) -> str:
        return "<%s %s>" % (self.http_method, self.key())


class Reply:
    def __init__(self, status: int = 200, body: str = "", hang: bool = False, headers=None) -> None:
        self.status, self.body, self.hang, self.headers = status, body, hang, headers or {}


class FakeVK:
    def __init__(self) -> None:
        self.calls: List[FakeCall] = []
        self.pages: Dict[str, str] = {
            "id.vk.com/not_robot_captcha": captcha_page(
                "checkbox", "https://static.vk.com/vkid/1.1.1276/not_robot_captcha.js"
            ),
            "static.vk.com/vkid/1.1.1276/not_robot_captcha.js": CAPTCHA_SCRIPT,
        }
        self.status: Dict[str, int] = {}
        self.methods: Dict[str, str] = {
            "captchaNotRobot.settings": '{"response":{"status":"OK","sensors_delay":100,"bridge_sensors_list":["cursor","accelerometer","keyboard"]}}',
            "captchaNotRobot.componentDone": '{"response":{"status":"OK"}}',
            "captchaNotRobot.check": '{"response":{"status":"OK","success_token":"SUCCESS-TOKEN","show_captcha_type":"checkbox"}}',
            "captchaNotRobot.endSession": '{"response":{"status":"OK"}}',
        }
        self.headers: Dict[str, List[tuple]] = {}
        self.next: Dict[str, List[Reply]] = {}
        # hooks[key](call) -> Reply answers a key itself.
        self.hooks: Dict[str, Callable[[FakeCall], Reply]] = {}
        self.port = 0
        self._runner: Optional[web.AppRunner] = None

    def set(self, key: str, body: str) -> None:
        if key.startswith("captchaNotRobot."):
            self.methods[key] = body
        else:
            self.pages[key] = body

    def queue(self, key: str, *replies: Reply) -> None:
        self.next.setdefault(key, []).extend(replies)

    def call_keys(self) -> List[str]:
        return [c.key() for c in self.calls]

    def call(self, key: str) -> FakeCall:
        for c in self.calls:
            if c.key() == key:
                return c
        raise AssertionError("no %s request; requests: %s" % (key, self.call_keys()))

    def calls_of(self, key: str) -> List[FakeCall]:
        return [c for c in self.calls if c.key() == key]

    async def handle(self, request: web.Request) -> web.StreamResponse:
        raw = await request.read()
        call = FakeCall(request, raw)
        self.calls.append(call)
        key = call.key()
        q = self.next.get(key)
        reply: Optional[Reply] = None
        if q:
            reply = q.pop(0)
        elif key in self.hooks:
            reply = self.hooks[key](call)
        if reply is not None:
            if reply.hang:
                await asyncio.sleep(30)
            hdrs = CIMultiDict()
            for k, v in reply.headers.items() if isinstance(reply.headers, dict) else reply.headers:
                hdrs.add(k, v)
            return web.Response(status=reply.status or 200, text=reply.body, headers=hdrs)
        status = self.status.get(key, 200)
        body = self.methods.get(key, "") if call.host in API_HOSTS else self.pages.get(key, "")
        hdrs = CIMultiDict()
        for k, v in self.headers.get(key, []):
            hdrs.add(k, v)
        if body == "" and status == 200 and "Location" not in hdrs:
            status = 404
        return web.Response(status=status, text=body, headers=hdrs)

    async def start(self, server_ctx: ssl.SSLContext) -> None:
        app = web.Application()
        app.router.add_route("*", "/{tail:.*}", self.handle)
        self._runner = web.AppRunner(app, handler_cancellation=True)
        await self._runner.setup()
        site = web.TCPSite(self._runner, "127.0.0.1", 0, ssl_context=server_ctx)
        await site.start()
        self.port = site._server.sockets[0].getsockname()[1]  # type: ignore[union-attr]

    async def close(self) -> None:
        if self._runner is not None:
            await self._runner.cleanup()


class FakeResolver(aiohttp.abc.AbstractResolver):
    """VK's hosts resolve to the fake VK; any other host is a numeric address
    and stays as it is."""

    def __init__(self, port: int) -> None:
        self.port = port

    async def resolve(self, host: str, port: int = 0, family: int = socket.AF_INET):
        if host in VK_HOSTS:
            target, port = "127.0.0.1", self.port
        else:
            target = host
        return [
            {"hostname": host, "host": target, "port": port, "family": socket.AF_INET, "proto": 0, "flags": socket.AI_NUMERICHOST}
        ]

    async def close(self) -> None:
        pass


_CA = trustme.CA()
_SERVER_CERT = _CA.issue_cert(*VK_HOSTS)


def server_context() -> ssl.SSLContext:
    ctx = ssl.create_default_context(ssl.Purpose.CLIENT_AUTH)
    _SERVER_CERT.configure_cert(ctx)
    return ctx


def client_context() -> ssl.SSLContext:
    ctx = ssl.create_default_context()
    _CA.configure_trust(ctx)
    return ctx


def attach(solver: CaptchaSolver, fake: FakeVK, waits: Optional[list] = None) -> CaptchaSolver:
    """Route the solver's requests to the fake VK; the person's waits are
    recorded instead of waited."""
    port = fake.port
    solver._connector_factory = lambda: aiohttp.TCPConnector(resolver=FakeResolver(port), ssl=client_context())

    async def no_wait(until: float) -> None:
        if waits is not None:
            waits.append(until)

    solver._wait = no_wait
    return solver


